import React, { createContext, useContext, useState, useEffect, useCallback, ReactNode } from 'react';
import { HistoryEntry, AnalysisData } from '../types';
import { saveHistoryToDB, loadHistoryFromDB, clearHistoryDB } from '../utils/idb';
import { dataUrlToBlob, createThumbnail, blobToDataUrl } from '../utils/fileUtils';
